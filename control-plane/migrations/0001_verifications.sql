-- Migration 0001: verifications (THE LOG) + verification_raw sidecar
-- Implements: Phase-1 spec §3.2 (Door 2), §4.1
-- The append-only log of every verification result, with complete provenance.
-- Enforced append-only via grants (see 0005_grants.sql).

-- =============================================================================
-- verifications — THE LOG (append-only, indefinite retention)
-- =============================================================================

CREATE TABLE IF NOT EXISTS verifications (
    -- Identity & time
    id uuid PRIMARY KEY,  -- App-generated UUIDv7 (time-ordered for insert locality)
    request_id uuid NOT NULL,  -- NOT UNIQUE (retries may repeat on append-only log)
    checked_at timestamptz NOT NULL,  -- Verdict time, UTC
    created_at timestamptz NOT NULL DEFAULT now(),  -- Insert time, UTC

    -- Email identity (Door 3 — frozen hashing scheme)
    -- NULLABLE by design: invalid_syntax/unparseable rows carry NULL (§3.2.7)
    email_hash bytea,  -- 32-byte HMAC-SHA256 of normalized email
    hash_scheme text,  -- e.g., 'norm/v1+hmac-sha256/v1'
    domain text,  -- Normalized domain (punycode/lowercased), in clear
    provider_canonical_hash bytea,  -- Provider-aware canonical hash (OQ-2, §3.3.5)
    local_part_len smallint,  -- Non-reversible shape signal

    -- The verdict (Door 4 — frozen vocabularies)
    status text NOT NULL,
    reason text NOT NULL,
    confidence smallint NOT NULL,
    recommendation text NOT NULL,

    -- Verdict detail (structured)
    flags jsonb NOT NULL,  -- Boolean facts about the address
    signals jsonb NOT NULL,  -- Open evidence bag

    -- Promoted typed column for analytics/grouping (§3.2.2, M3)
    mx_provider text,  -- google|o365|yahoo|self|other (permanent grouping dimension)

    -- Policy & contract provenance
    policy_key text NOT NULL,
    policy_version integer NOT NULL,
    api_version text NOT NULL,  -- Always 'v1' in Phase 1

    -- Engine provenance
    verifier_ip inet,  -- Node IP that ran SMTP; NULL in P1 (no SMTP)
    node_id text,  -- Node id (FK-less — must survive node deletion)
    engine_version text,  -- Composite: 'rack@x.y.z+gem@a.b.c'
    engine_core_version text,  -- Gem version alone for bucketing
    config_fingerprint text NOT NULL,  -- Fingerprint of config that produced verdict

    -- Engine-specific fields (preserved distinct from our verdict)
    engine_validation_type text,  -- truemail's own validation_type
    engine_success boolean,  -- truemail's own success boolean

    -- Execution metadata
    from_cache boolean NOT NULL,  -- Served from cache? (calibration excludes true)
    latency_ms integer,  -- Processing time in milliseconds

    -- Integrity constraints (Door 3 + Door 4 enforcement)
    CONSTRAINT valid_confidence CHECK (confidence BETWEEN 0 AND 100),
    CONSTRAINT valid_status CHECK (status IN (
        'valid', 'invalid', 'risky', 'unknown'
    )),
    CONSTRAINT valid_recommendation CHECK (recommendation IN (
        'send', 'review', 'skip'
    )),
    CONSTRAINT valid_reason CHECK (reason IN (
        -- Phase 1 reasons (cheap layers)
        'invalid_syntax', 'invalid_domain', 'no_mx', 'null_mx', 'dns_error',
        'disposable', 'blacklisted_domain', 'blacklisted_mx', 'spam_trap',
        'role_account', 'whitelisted', 'provider_no_smtp', 'plausible',
        -- Phase 2+ reasons (reserved now, additive)
        'accepted', 'mailbox_not_found', 'mailbox_full', 'catch_all', 'accept_all',
        'greylisted', 'smtp_blocked', 'smtp_timeout', 'smtp_error', 'connection_failed',
        -- Phase 6+ reasons (reserved)
        'external_verified',
        -- Phase 7+ reasons (reserved)
        'historical_bounce',
        -- Catch-all
        'unknown_error'
    )),
    CONSTRAINT domain_normalized CHECK (domain IS NULL OR domain = lower(domain)),
    CONSTRAINT hash_scheme_linkage CHECK (
        (email_hash IS NULL) = (hash_scheme IS NULL)
    )
);

COMMENT ON TABLE verifications IS 'THE LOG: append-only record of every verification, with provenance. Never updated or deleted (enforced via grants).';
COMMENT ON COLUMN verifications.id IS 'Time-ordered UUIDv7 generated by application for insert locality.';
COMMENT ON COLUMN verifications.email_hash IS 'HMAC-SHA256 of normalized email (bytea, 32 bytes). NULL for invalid_syntax/unparseable.';
COMMENT ON COLUMN verifications.hash_scheme IS 'Scheme tag (e.g., norm/v1+hmac-sha256/v1). NULL iff email_hash is NULL.';
COMMENT ON COLUMN verifications.domain IS 'Normalized domain (lowercase ASCII/punycode). NULL when not extractable. Plain text, not citext.';
COMMENT ON COLUMN verifications.provider_canonical_hash IS 'Provider-aware canonical hash (e.g., Gmail dot-stripping). NULL when provider unknown.';
COMMENT ON COLUMN verifications.mx_provider IS 'Promoted typed column: classified provider for flywheel grouping.';
COMMENT ON COLUMN verifications.config_fingerprint IS 'Fingerprint of engine+layer+policy config. NOT NULL — always computable.';
COMMENT ON COLUMN verifications.from_cache IS 'Served from cache? Calibration excludes rows with from_cache=true.';
COMMENT ON COLUMN verifications.node_id IS 'FK-less text: logged node_id must survive node deletion.';

-- Indexes for analytics/queries (§4.1)
CREATE INDEX IF NOT EXISTS idx_verifications_email_hash ON verifications (email_hash) WHERE email_hash IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_verifications_domain ON verifications (domain) WHERE domain IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_verifications_checked_at ON verifications (checked_at);
CREATE INDEX IF NOT EXISTS idx_verifications_mx_provider ON verifications (mx_provider) WHERE mx_provider IS NOT NULL;

-- =============================================================================
-- verification_raw — 1:1 sidecar for untouched engine JSON
-- =============================================================================
-- Retention-managed store (RANGE-partitioned by month, DROP PARTITION for aging).
-- The ONLY table subject to retention deletion. Keeps verifications truly append-only.

CREATE TABLE IF NOT EXISTS verification_raw (
    verification_id uuid NOT NULL,  -- FK to verifications(id)
    raw jsonb,  -- Untouched engine JSON response
    created_at timestamptz NOT NULL DEFAULT now(),  -- Partition key

    PRIMARY KEY (verification_id, created_at),  -- Composite PK for partitioning
    FOREIGN KEY (verification_id) REFERENCES verifications(id) ON DELETE CASCADE
) PARTITION BY RANGE (created_at);

COMMENT ON TABLE verification_raw IS '1:1 sidecar for raw engine JSON. RANGE-partitioned by month. Retention = DROP PARTITION (never UPDATE). This is the ONLY retention-managed store.';

-- Create initial partitions (2026-07 through 2026-09 as examples)
-- Production: automate partition creation ahead of time

CREATE TABLE IF NOT EXISTS verification_raw_2026_07 PARTITION OF verification_raw
    FOR VALUES FROM ('2026-07-01') TO ('2026-08-01');

CREATE TABLE IF NOT EXISTS verification_raw_2026_08 PARTITION OF verification_raw
    FOR VALUES FROM ('2026-08-01') TO ('2026-09-01');

CREATE TABLE IF NOT EXISTS verification_raw_2026_09 PARTITION OF verification_raw
    FOR VALUES FROM ('2026-09-01') TO ('2026-10-01');

COMMENT ON TABLE verification_raw_2026_07 IS 'Partition for July 2026. Retention: DROP PARTITION after ~90 days (§3.2.6).';
COMMENT ON TABLE verification_raw_2026_08 IS 'Partition for August 2026. Retention: DROP PARTITION after ~90 days.';
COMMENT ON TABLE verification_raw_2026_09 IS 'Partition for September 2026. Retention: DROP PARTITION after ~90 days.';
